IF EXISTS (SELECT * FROM sys.databases WHERE name = 'QL_THI')
BEGIN
    ALTER DATABASE QL_THI SET SINGLE_USER WITH ROLLBACK IMMEDIATE;
    DROP DATABASE QL_THI;
END
GO

CREATE DATABASE QL_THI;
GO
USE QL_THI;
GO

CREATE TABLE KHOA (
	MAKHOA VARCHAR(10) PRIMARY KEY,
	TENKHOA NVARCHAR(20)
)
GO

CREATE TABLE LOP (
	MALOP VARCHAR(10) PRIMARY KEY,
	TENLOP NVARCHAR(40),
	MAKHOA VARCHAR(10),
	FOREIGN KEY (MAKHOA) REFERENCES KHOA(MAKHOA)
)
GO

CREATE TABLE SINH_VIEN (
	MASV VARCHAR(10) PRIMARY KEY,
	HOTEN NVARCHAR(30),
	NGAYSINH DATE,
	NOISINH NVARCHAR(40),
	PHAI NVARCHAR(3),
	DANTOC NVARCHAR(10),
	MALOP VARCHAR(10),
	FOREIGN KEY (MALOP) REFERENCES LOP(MALOP)
)
GO

CREATE TABLE MON_THI (
	MAMT VARCHAR(10) PRIMARY KEY,
	TENMT NVARCHAR(30),
	THOIGIAN INT,
	NGAYTHI DATE,
	BUOITHI NVARCHAR(10)
)
GO

CREATE TABLE KET_QUA_THI (
	MASV VARCHAR(10),
	MAMT VARCHAR(10),
	DIEM FLOAT,
	PRIMARY KEY(MASV, MAMT),
	FOREIGN KEY (MASV) REFERENCES SINH_VIEN(MASV),
	FOREIGN KEY (MAMT) REFERENCES MON_THI(MAMT)
)
GO

