SELECT HOTEN, NOISINH
FROM SINH_VIEN
WHERE NOISINH = 'TRA VINH' OR NOISINH = 'CAN THO';

SELECT L.MALOP, L.TENLOP, COUNT(SV.MASV) AS SoLuongSinhVien
FROM LOP L, SINH_VIEN SV
WHERE L.MALOP = SV.MALOP
GROUP BY L.MALOP, L.TENLOP;

SELECT SV.HOTEN, L.TENLOP, K.TENKHOA
FROM SINH_VIEN SV
JOIN LOP L ON SV.MALOP = L.MALOP
JOIN KHOA K ON L.MAKHOA = K.MAKHOA;

SELECT SV.HOTEN, KQ.DIEM, KQ.MAMT
FROM SINH_VIEN SV
JOIN KET_QUA_THI KQ ON SV.MASV = KQ.MASV
WHERE KQ.MAMT = '001' AND KQ.DIEM = (
	SELECT MAX(DIEM)
	FROM KET_QUA_THI
	WHERE MAMT = '001' 
)

SELECT SV.HOTEN, KQ.DIEM, KQ.MAMT
FROM SINH_VIEN SV
JOIN KET_QUA_THI KQ ON SV.MASV = KQ.MASV
WHERE KQ.MAMT = '001' AND KQ.DIEM = (
	SELECT MIN(DIEM)
	FROM KET_QUA_THI
	WHERE MAMT = '001' 
);

SELECT HOTEN
FROM SINH_VIEN
WHERE MASV NOT IN (
	SELECT MASV
	FROM KET_QUA_THI
);

SELECT M.MAMT, M.TENMT, COUNT(KQ.MASV) AS SoLuongSinhVien
FROM MON_THI M
LEFT JOIN KET_QUA_THI KQ ON M.MAMT = KQ.MAMT
GROUP BY M.MAMT, M.TENMT;

SELECT MT.BUOITHI, COUNT(KQ.MASV) AS SO_LUONG_SINH_VIEN
FROM MON_THI MT
LEFT JOIN KET_QUA_THI KQ ON MT.MAMT = KQ.MAMT
GROUP BY MT.BUOITHI;


